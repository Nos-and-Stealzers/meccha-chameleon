"""Build models.js from the Kenney CC0 packs: embeds every 'pack:model' key referenced in the game's JS.
Usage: python tools/pack_models.py <assets_root>   (assets_root holds the unzipped kenney packs, one folder per pack)
"""
import base64, glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'assets', 'kenney')
PACKS = {'f': 'furniture-kit', 'food': 'food-kit', 'surv': 'survival-kit', 'mkt': 'mini-market', 'toy': 'toy-car-kit',
         'hol': 'holiday-kit', 'arc': 'mini-arcade', 'nat': 'nature-kit', 'pir': 'pirate-kit', 'grave': 'graveyard-kit',
         'plat': 'platformer-kit', 'city': 'city-kit-commercial'}

src = ''
for f in ['maps.js', 'game.js', 'ui.js', 'chars.js', 'props.js']:
    p = os.path.join(ROOT, f)
    if os.path.exists(p):
        src += open(p, encoding='utf8').read()
keys = sorted(set(re.findall(r"""['"`]((?:%s):[A-Za-z0-9_\-]+)['"`]""" % '|'.join(PACKS), src)))
extra = os.path.join(ROOT, 'tools', 'extra_models.txt')
if os.path.exists(extra):
    keys = sorted(set(keys) | {l.strip() for l in open(extra) if ':' in l})

out, tex, missing, total = {}, {}, [], 0
for k in keys:
    pack, name = k.split(':', 1)
    hits = glob.glob(os.path.join(ASSETS, PACKS[pack], 'Models', 'GL*', name + '.glb'))
    if not hits:
        missing.append(k)
        continue
    data = open(hits[0], 'rb').read()
    total += len(data)
    out[k] = [pack, base64.b64encode(data).decode()]
    if pack not in tex:
        t = glob.glob(os.path.join(ASSETS, PACKS[pack], 'Models', 'GL*', 'Textures', 'colormap.png'))
        if t:
            tex[pack] = 'data:image/png;base64,' + base64.b64encode(open(t[0], 'rb').read()).decode()

with open(os.path.join(ROOT, 'models.js'), 'w', encoding='utf8') as fh:
    fh.write("'use strict';\n/* Generated by tools/pack_models.py. 3D models: Kenney (kenney.nl), CC0 1.0. */\n")
    fh.write('const MODEL_TEX = ' + json.dumps(tex) + ';\n')
    fh.write('const MODEL_SRC = {\n')
    for k, v in out.items():
        fh.write('  %s: %s,\n' % (json.dumps(k), json.dumps(v)))
    fh.write('};\n')
print('models', len(out), 'raw KB', total // 1024, 'missing', missing)
