"""Build sounds.js from the Kenney CC0 audio packs (Impact Sounds, Interface Sounds).
Usage: python tools/pack_sounds.py [assets_root]   (assets_root holds the unzipped packs, default assets/kenney)
Each group is a list of base64 OGG variations; game.js picks one at random and falls back to its synth sound
if a group is missing or fails to decode.
"""
import base64, glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'assets', 'kenney')
GROUPS = {
    'step_wood': ('impact-sounds', 'footstep_wood_*.ogg'),
    'step_carpet': ('impact-sounds', 'footstep_carpet_*.ogg'),
    'step_concrete': ('impact-sounds', 'footstep_concrete_*.ogg'),
    'step_grass': ('impact-sounds', 'footstep_grass_*.ogg'),
    'soft': ('impact-sounds', 'impactSoft_medium_*.ogg'),
    'splat': ('impact-sounds', 'impactSoft_heavy_*.ogg'),
    'punch': ('impact-sounds', 'impactPunch_medium_*.ogg'),
    'click': ('interface-sounds', 'click_*.ogg'),
    'tick': ('interface-sounds', 'tick_*.ogg'),
}

out, total = {}, 0
for key, (pack, pat) in GROUPS.items():
    files = sorted(glob.glob(os.path.join(ASSETS, pack, 'Audio', pat)))
    if not files:
        sys.exit('missing %s/%s' % (pack, pat))
    out[key] = []
    for f in files:
        data = open(f, 'rb').read()
        total += len(data)
        out[key].append(base64.b64encode(data).decode())

with open(os.path.join(ROOT, 'sounds.js'), 'w', encoding='utf8', newline='\n') as fh:
    fh.write("'use strict';\n/* Generated by tools/pack_sounds.py. Sounds: Kenney (kenney.nl) Impact Sounds + Interface Sounds, CC0 1.0. */\n")
    fh.write('const SOUND_SRC = {\n')
    for key, lst in out.items():
        fh.write('  %s: [%s],\n' % (key, ', '.join("'%s'" % b for b in lst)))
    fh.write('};\n')
print('groups', len(out), 'files', sum(len(v) for v in out.values()), 'bytes', total)
